def clean_street_name(address_line):
    parts = address_line.split(',')
    if len(parts) >= 1:
        address_part = parts[0].strip()
        street = re.sub(r'^\d+\s+', '', address_part).strip()
        street = re.sub(r'\s+(UNIT|APT|STE|#).*$', '', street, flags=re.IGNORECASE)
        # Strip Gxx (Group/Garage/Garden units) and BLDG
        street = re.sub(r'\sG\d+$', '', street) 
        street = re.sub(r'\sBLDG\s?\d+$', '', street, flags=re.IGNORECASE)
        # Also clean up city/state if they leaked in
        street = street.split(' Hilliard')[0].split(' Columbus')[0]
        return street.upper().strip()
    return ""

def get_house_number_street(address_line):
    parts = address_line.split(',')
    if len(parts) >= 1:
        return parts[0].strip().upper()
    return ""

def main():
    print("Starting Final Mega Batch Processing...")
    
    addresses_to_process = []
    with open(INPUT_FILE, 'r') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("DEBUG") or line.startswith("BATCH"):
                continue
            addresses_to_process.append(line)
            
    print(f"Loaded {len(addresses_to_process)} addresses.")
    
    results = []
    excluded = []
    manual_review = []
    
    for addr in addresses_to_process:
        street = clean_street_name(addr)
        house_street = get_house_number_street(addr)
        
        # Check Explicit Excludes
        is_excluded = False
        for excl in EXPLICIT_EXCLUDES:
            if excl in house_street:
                excluded.append({'address': addr, 'reason': 'Explicit Blacklist'})
                is_excluded = True
                break
        if is_excluded:
            continue

        # Check Excluded Streets
        if any(street.startswith(excl) for excl in EXCLUDED_STREET_NAMES):
            excluded.append({'address': addr, 'reason': 'Commercial/Industrial Street'})
            continue

        # Look up in Map
        info = STREET_MAP.get(street)
        if not info:
             # Normalize
            norm_street = street.replace("'", "").replace(".", "")
            for k, v in STREET_MAP.items():
                if k.replace("'", "").replace(".", "") == norm_street:
                    info = v
                    break
        
        if info:
            if info['class'] == 'Residential':
                results.append({
                    'address': addr,
                    'classification': 'Residential',
                    'property_type': info['type'],
                    'source': 'Verified Street Map'
                })
            elif info['class'] == 'Check_Specific':
                # Assume Residential if not excluded
                results.append({
                    'address': addr,
                    'classification': 'Residential',
                    'property_type': info['type'] + ' (Unverified Specific)',
                    'source': 'Street Map (Mixed Street)'
                })
            elif info['class'] == 'Manual_Review':
                manual_review.append(addr)
        else:
            manual_review.append(addr)
            
    print(f"Verified Residential: {len(results)}")
    print(f"Excluded: {len(excluded)}")
    print(f"Manual Review Needed: {len(manual_review)}")
    
    # Save Valid Results
    file_exists = os.path.isfile(OUTPUT_FILE)
    # Check if we should append or overwrite. Given we are processing the batch completely, verify if file has content.
    # The batch script might have written some? I should probably Append.
    
    with open(OUTPUT_FILE, 'a', newline='', encoding='utf-8') as f:
        fieldnames = ['address', 'classification', 'property_type', 'source']
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        if not file_exists:
            writer.writeheader()
        for res in results:
            writer.writerow(res)
            
    # Save Excluded
    with open(EXCLUDED_FILE, 'a', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        for excl in excluded:
            writer.writerow([excl['address'], excl['reason']])

    # Save Manual Review
    if manual_review:
        with open('output/manual_review_needed.txt', 'w') as f:
            for item in manual_review:
                f.write(item + "\n")

    print(f"Process Complete. Valid: {len(results)}, Excluded: {len(excluded)}")

if __name__ == "__main__":
    main()
